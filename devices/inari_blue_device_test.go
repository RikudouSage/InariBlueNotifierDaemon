package devices

import (
	"InariBlueNotifier/patterns"
	"bytes"
	"os"
	"path/filepath"
	"testing"
)

func TestApplyPatternRegisterWrites(t *testing.T) {
	steady := patterns.Steady
	steady.Brightness = 123
	steady.Channels = []uint8{0, 2}
	animation := patterns.RapidBlink
	animation.Channels = []uint8{1}
	off := patterns.Steady
	off.Brightness = 0

	tests := []struct {
		name    string
		pattern patterns.Pattern
		want    []byte
	}{
		{"steady selected channels", steady, []byte{
			0x30, 0x00, 0x01, 0x01,
			0x37, 0x00, 0x38, 0x00, 0x39, 0x00, 0x34, 123, 0x31, 0x0f,
			0x3a, 0x00, 0x3b, 0x00, 0x3c, 0x00, 0x35, 123, 0x32, 0x0f,
			0x3d, 0x00, 0x3e, 0x00, 0x3f, 0x00, 0x36, 123, 0x33, 0x0f,
			0x01, 0x00, 0x01, 0x01, 0x30, 0x05,
		}},
		{"steady all channels", patterns.Steady, []byte{
			0x30, 0x00, 0x01, 0x01,
			0x37, 0x00, 0x38, 0x00, 0x39, 0x00, 0x34, 0xff, 0x31, 0x0f,
			0x3a, 0x00, 0x3b, 0x00, 0x3c, 0x00, 0x35, 0xff, 0x32, 0x0f,
			0x3d, 0x00, 0x3e, 0x00, 0x3f, 0x00, 0x36, 0xff, 0x33, 0x0f,
			0x01, 0x00, 0x01, 0x01, 0x30, 0x07,
		}},
		{"animation", animation, []byte{
			0x30, 0x00, 0x01, 0x01,
			0x37, 0x01, 0x38, 0x01, 0x39, 0x00, 0x34, 0xff, 0x31, 0x1f,
			0x3a, 0x01, 0x3b, 0x01, 0x3c, 0x00, 0x35, 0xff, 0x32, 0x1f,
			0x3d, 0x01, 0x3e, 0x01, 0x3f, 0x00, 0x36, 0xff, 0x33, 0x1f,
			0x01, 0x00, 0x01, 0x01, 0x30, 0x02,
		}},
		{"zero brightness disables", off, []byte{0x30, 0x00}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			file, err := os.Create(filepath.Join(t.TempDir(), "register-writes"))
			if err != nil {
				t.Fatal(err)
			}
			defer file.Close()
			device := &InariBlueDevice{deviceFile: file}
			if err := tt.pattern.Validate(); err != nil {
				t.Fatalf("validate pattern: %v", err)
			}
			if err := device.applyPattern(tt.pattern); err != nil {
				t.Fatalf("apply pattern: %v", err)
			}
			got, err := os.ReadFile(file.Name())
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(got, tt.want) {
				t.Fatalf("register writes = % x, want % x", got, tt.want)
			}
		})
	}
}
